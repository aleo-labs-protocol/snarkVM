    // This test verifies that `contains_dynamic_call` returns `false` for a function
    // that contains only static `call` instructions (no `call.dynamic`).
    #[test]
    fn test_contains_dynamic_call_with_static_calls() {
        // `Process::load` always includes `credits.aleo`, which has no dynamic calls.
        let process = Process::<CurrentNetwork>::load().unwrap();
        let stack = process.get_stack("credits.aleo").unwrap();
        // `transfer_public` uses only static operations — no `call.dynamic`.
        let function_name = Identifier::from_str("transfer_public").unwrap();
        assert!(!stack.contains_dynamic_call(&function_name).unwrap());
    }

    // This test verifies that `contains_dynamic_call` returns `true` for a function
    // that directly contains a `call.dynamic` instruction.
    #[test]
    fn test_contains_dynamic_call_with_dynamic_calls() {
        // Define a program with a function that issues a bare `call.dynamic` (no inputs or outputs).
        let program = Program::<CurrentNetwork>::from_str(
            r"
program dynamic_test.aleo;

function dynamic_func:
    input r0 as field.public;
    input r1 as field.public;
    input r2 as field.public;
    call.dynamic r0 r1 r2;",
        )
        .unwrap();
        // Add the program to a fresh process (no deployment needed for stack inspection).
        let process = Process::<CurrentNetwork>::load().unwrap();
        process.lock().add_program(&program).unwrap();
        let stack = process.get_stack("dynamic_test.aleo").unwrap();
        // `dynamic_func` contains a `call.dynamic` instruction and must be detected.
        let function_name = Identifier::from_str("dynamic_func").unwrap();
        assert!(stack.contains_dynamic_call(&function_name).unwrap());
    }

    // This test verifies that `contains_dynamic_call` returns `true` for a function that
    // transitively reaches a `call.dynamic` via a static external call.
    #[test]
    fn test_contains_dynamic_call_transitive() {
        // Define a helper program whose function issues `call.dynamic`.
        let helper_program = Program::<CurrentNetwork>::from_str(
            r"
program helper.aleo;

function dynamic_helper:
    input r0 as field.public;
    input r1 as field.public;
    input r2 as field.public;
    call.dynamic r0 r1 r2;",
        )
        .unwrap();
        // Define a caller program that statically calls `helper.aleo/dynamic_helper`.
        let caller_program = Program::<CurrentNetwork>::from_str(
            r"
import helper.aleo;

program caller.aleo;

function caller_func:
    input r0 as field.public;
    input r1 as field.public;
    input r2 as field.public;
    call helper.aleo/dynamic_helper r0 r1 r2;",
        )
        .unwrap();
        // Add programs in dependency order: helper first, then caller.
        let process = Process::<CurrentNetwork>::load().unwrap();
        process.lock().add_program(&helper_program).unwrap();
        process.lock().add_program(&caller_program).unwrap();
        let stack = process.get_stack("caller.aleo").unwrap();
        // `caller_func` transitively reaches `call.dynamic` via `helper.aleo/dynamic_helper`.
        let function_name = Identifier::from_str("caller_func").unwrap();
        assert!(stack.contains_dynamic_call(&function_name).unwrap());
    }

    // This test verifies that `console_matches_register_type` accepts every value whose layout
    // matches its register type and rejects every mismatched combination.
    #[test]
    fn test_console_matches_register_type() {
        let program_id = "test_matcher.aleo";

        // A program that defines the internal record, self-referential future, and external import
        // needed to exercise every `RegisterType` variant. This is necessary as ExternalRecords and
        // Records have different RegisterType but the same Value variant (if they refer to the same
        // static-record type).
        let program_str = r"
            import credits.aleo;
    
            program test_matcher.aleo;
    
            record token:
                owner as address.private;
                amount as u64.private;
    
            function make_future:
                input r0 as u64.public;
                async make_future r0 into r1;
                output r1 as test_matcher.aleo/make_future.future;
    
            finalize make_future:
                input r0 as u64.public;
                add r0 r0 into r1;
            ";

        let owner: &str = "aleo1d5hg2z3ma00382pngntdp68e74zv54jdxy249qhaujhks9c72yrs33ddah";

        // `(register type, value)` pairs covering every `RegisterType` variant. Each value matches its
        // own register type and no other register type in the list.
        let cases = vec![
            ("boolean", "true".to_string()),
            ("field", "1field".to_string()),
            ("group", "0group".to_string()),
            ("scalar", "1scalar".to_string()),
            ("u8", "1u8".to_string()),
            ("u16", "1u16".to_string()),
            ("u32", "1u32".to_string()),
            ("u64", "1u64".to_string()),
            ("u128", "1u128".to_string()),
            ("i8", "1i8".to_string()),
            ("i16", "1i16".to_string()),
            ("i32", "1i32".to_string()),
            ("i64", "1i64".to_string()),
            ("i128", "1i128".to_string()),
            ("[u8; 3u32]", "[1u8, 2u8, 3u8]".to_string()),
            // A static Record. `amount` distinguishes its layout from the `credits` record, used for
            // the ExternalRecord case.
            (
                "token.record",
                format!(
                    "{{ owner: {owner}.private, amount: 5u64.private, _nonce: 0group.public, _version: 0u8.public }}"
                ),
            ),
            // An ExternalRecord. `microcredits` distinguishes its layout from that of the `token` record.
            (
                "credits.aleo/credits.record",
                format!(
                    "{{ owner: {owner}.private, microcredits: 5u64.private, _nonce: 0group.public, _version: 0u8.public }}"
                ),
            ),
            // A future whose program ID, function name, and argument match `make_future`.
            (
                "test_matcher.aleo/make_future.future",
                "{ program_id: test_matcher.aleo, function_name: make_future, arguments: [ 5u64 ] }".to_string(),
            ),
            ("dynamic.record", format!("{{ owner: {owner}, _root: 0field, _nonce: 0group, _version: 0u8 }}")),
            (
                "dynamic.future",
                "{ _program_id: credits.aleo, _function_name: transfer_public, _checksum: 0field }".to_string(),
            ),
        ];

        // Build a stack for a program that exercises every register type variant.
        let program = Program::<CurrentNetwork>::from_str(program_str).unwrap();
        let process = Process::<CurrentNetwork>::load().unwrap();
        process.lock().add_program(&program).unwrap();
        let stack = process.get_stack(program_id).unwrap();

        let types: Vec<_> = cases.iter().map(|(t, _)| RegisterType::<CurrentNetwork>::from_str(t).unwrap()).collect();
        let values: Vec<_> = cases.iter().map(|(_, v)| Value::<CurrentNetwork>::from_str(v).unwrap()).collect();

        // Every value matches its own register type (all correct combinations) and fails against
        // every other register type in the matrix (many incorrect combinations per type).
        for (i, value) in values.iter().enumerate() {
            for (j, register_type) in types.iter().enumerate() {
                let result = console_matches_register_type(&*stack, value, register_type);
                if i == j {
                    assert!(result.is_ok(), "expected '{}' to match '{}': {result:?}", cases[i].1, cases[j].0);
                } else {
                    assert!(result.is_err(), "expected '{}' to not match '{}'", cases[i].1, cases[j].0);
                }
            }
        }
    }

    fn declared_held(stack: &Stack<CurrentNetwork>) -> usize {
        let program = stack.program();
        program
            .functions()
            .keys()
            .chain(program.records().keys())
            .filter(|name| stack.contains_proving_key(name))
            .count()
    }

    fn listed(stack: &Stack<CurrentNetwork>) -> Vec<Identifier<CurrentNetwork>> {
        stack.proving_keys().into_iter().map(|(name, _)| name).collect()
    }

    #[test]
    fn test_proving_keys_lists_the_held_function_and_translation_keys() {
        let program = Program::<CurrentNetwork>::from_str(
            r"
program listing.aleo;

record token:
    owner as address.private;

function held:
    input r0 as u8.public;

function verifying_only:
    input r0 as u8.public;",
        )
        .unwrap();
        let process = crate::test_helpers::sample_process(&program);
        let stack = process.get_stack(program.id()).unwrap();
        let (_, proving_key, verifying_key) = crate::test_helpers::sample_key();
        let [held, verifying_only, token] =
            ["held", "verifying_only", "token"].map(|n| Identifier::from_str(n).unwrap());
        let token_key = ProvingKey::new(Arc::new((*proving_key).clone()));
        stack.insert_proving_key(&held, proving_key.clone()).unwrap();
        stack.insert_proving_key(&token, token_key.clone()).unwrap();
        stack.insert_verifying_key(&verifying_only, verifying_key).unwrap();
        let keys = stack.proving_keys();
        assert_eq!(keys.iter().map(|(name, _)| *name).collect::<Vec<_>>(), [held, token]);
        assert!(std::ptr::eq(&*keys[0].1, &*proving_key));
        assert!(std::ptr::eq(&*keys[1].1, &*token_key));
    }

    #[test]
    fn test_proving_keys_loads_no_credits_key_and_omits_a_removed_one() {
        let process = Process::<CurrentNetwork>::load().unwrap();
        let stack = process.get_stack("credits.aleo").unwrap();
        assert_eq!(declared_held(&stack), 0);
        let transfer_public = Identifier::from_str("transfer_public").unwrap();
        stack.insert_proving_key(&transfer_public, crate::test_helpers::sample_key().1).unwrap();
        assert_eq!(listed(&stack), [transfer_public]);
        assert_eq!(declared_held(&stack), 1);
        process.remove_proving_key(stack.program_id(), &transfer_public).unwrap();
        assert!(listed(&stack).is_empty());
        assert_eq!(declared_held(&stack), 0);
    }
