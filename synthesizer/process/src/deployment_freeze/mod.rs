//! The deployment freeze (ARC-0048, "Deployment Freeze by Validator Vote").
//!
//! Validators vote by signing a `freeze_vote` payload offline (see [`FreezeVote`]); anyone
//! submits signatures from a quorum of stake to `aleo_deployment_freeze.aleo/submit_votes`. From
//! [`DEPLOYMENT_FREEZE_CONSENSUS_VERSION`],
//! consensus reads one committed value, `aleo_deployment_freeze.aleo/freeze[0u8]`, and rejects every
//! deployment in a block at height `H` with `start <= H < end`, charging its fee and never
//! verifying it.
//!
//! The program source (`aleo_deployment_freeze.aleo`) is generated by `generate.py` in this directory.
//! The program is built into the protocol, like `credits.aleo`: every [`Process`] loads it at edition
//! 0, with the committed verifying key of `submit_votes` for its network, and it is never deployed.
//! Its name contains "aleo", which every deployment has been refused since `ConsensusVersion::V7`,
//! so no deployed program can share its ID.
//!
//! Before [`DEPLOYMENT_FREEZE_CONSENSUS_VERSION`] the program is loaded but unusable: the VM refuses
//! a transaction that executes it or a deployment that imports it, and its mappings do not exist
//! until the VM initializes them in the first block of that version. So until then a node behaves as
//! one without the program.

use crate::{Process, Stack};

use console::{
    account::{Address, PrivateKey, Signature},
    network::{ConsensusVersion, prelude::*},
    program::{Identifier, Literal, Plaintext, ProgramID, Value},
    types::Field,
};
use rand::SeedableRng;
use rand_chacha::ChaChaRng;
use snarkvm_ledger_store::{FinalizeStorage, FinalizeStore};
