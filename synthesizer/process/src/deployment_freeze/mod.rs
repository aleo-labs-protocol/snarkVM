    /// A vote signed the way `snarkos account sign --message '<literal>'` signs (the literal parsed
    /// as a `Value`, then `to_fields`) verifies with `sign.verify` on the program's `freeze_vote`
    /// struct, both when evaluated and in the circuit. A different signer, value or member order
    /// does not.
    #[test]
    fn test_account_sign_payload_verifies_in_program() {
        use circuit::network::AleoV0;
        use console::account::{Address, PrivateKey, Signature};

        let rng = &mut TestRng::default();
        let program = Program::<CurrentNetwork>::from_str(
            r"
program freeze_vote_check.aleo;

struct freeze_vote:
    aleo_deployment_freeze as boolean;
    network as u16;
    action as u8;
    duration as u32;
    nonce as u64;
    expires as u32;

function check:
    input r0 as signature.public;
    input r1 as address.public;
    input r2 as freeze_vote.public;
    sign.verify r0 r1 r2 into r3;
    output r3 as boolean.public;
",
        )
        .unwrap();
        let process = Process::<CurrentNetwork>::load().unwrap();
        process.lock().add_program(&program).unwrap();

        let literal = "{ aleo_deployment_freeze: true, network: 0u16, action: 1u8, duration: 28800u32, nonce: 0u64, expires: 23500000u32 }";
        // Exactly what `snarkos account sign` does for a non-raw message.
        let sign = |private_key: &PrivateKey<CurrentNetwork>, message: &str, rng: &mut TestRng| {
            let fields = Value::<CurrentNetwork>::from_str(message).unwrap().to_fields().unwrap();
            private_key.sign(&fields, rng).unwrap()
        };
        let signer = PrivateKey::<CurrentNetwork>::new(rng).unwrap();
        let other = PrivateKey::<CurrentNetwork>::new(rng).unwrap();
        let signer_address = Address::try_from(&signer).unwrap();

        let check = |signature: Signature<CurrentNetwork>, address: Address<CurrentNetwork>, rng: &mut TestRng| {
            let inputs = [
                Value::<CurrentNetwork>::from_str(&signature.to_string()).unwrap(),
                Value::from_str(&address.to_string()).unwrap(),
                Value::from_str(literal).unwrap(),
            ];
            let authorization = process
                .authorize::<AleoV0, _>(
                    &other,
                    program.id(),
                    Identifier::from_str("check").unwrap(),
                    inputs.iter(),
                    rng,
                )
                .unwrap();
            let evaluated = process.evaluate::<AleoV0>(authorization.replicate()).unwrap().outputs()[0].clone();
            let (response, _) = process.execute::<AleoV0, _>(authorization, rng).unwrap();
            assert_eq!(evaluated, response.outputs()[0], "evaluate and execute disagree");
            evaluated == Value::from_str("true").unwrap()
        };

        // The signer's signature over the literal verifies.
        assert!(check(sign(&signer, literal, rng), signer_address, rng));
        // Another signer's signature does not.
        assert!(!check(sign(&other, literal, rng), signer_address, rng));
        // A signature over a different value does not.
        let other_value = literal.replace("nonce: 0u64", "nonce: 1u64");
        assert!(!check(sign(&signer, &other_value, rng), signer_address, rng));
        // A signature over the same members in another order does not: struct fields include the
        // member names and their order.
        let reordered = "{ network: 0u16, aleo_deployment_freeze: true, action: 1u8, duration: 28800u32, nonce: 0u64, expires: 23500000u32 }";
        assert!(!check(sign(&signer, reordered, rng), signer_address, rng));
    }

    #[test]
    fn test_freeze_vote_parse_and_validate() {
        let vote = FreezeVote { network: 0, action: ACTION_FREEZE, duration: 28_800, nonce: 3, expires: 1_000_000 };
        let literal = vote.literal();
        assert_eq!(FreezeVote::parse::<CurrentNetwork>(&literal).unwrap(), vote);
        assert!(vote.validate().is_ok());
        // Reordered members, a false tag, a missing member or a wrong type are refused.
        let reordered = literal.replace("network: 0u16, action: 1u8", "action: 1u8, network: 0u16");
        assert!(FreezeVote::parse::<CurrentNetwork>(&reordered).is_err());
        let untagged = literal.replace("aleo_deployment_freeze: true", "aleo_deployment_freeze: false");
        assert!(FreezeVote::parse::<CurrentNetwork>(&untagged).is_err());
        let missing = literal.replace(", expires: 1000000u32", "");
        assert!(FreezeVote::parse::<CurrentNetwork>(&missing).is_err());
        let wrong_type = literal.replace("nonce: 3u64", "nonce: 3u32");
        assert!(FreezeVote::parse::<CurrentNetwork>(&wrong_type).is_err());
        // The action and duration rules.
        let with = |action, duration| FreezeVote { action, duration, ..vote }.validate();
        assert!(with(ACTION_FREEZE, FREEZE_DELAY).is_err());
        assert!(with(ACTION_FREEZE, FREEZE_DELAY + 1).is_ok());
        assert!(with(ACTION_FREEZE, MAX_FREEZE_BLOCKS).is_ok());
        assert!(with(ACTION_FREEZE, MAX_FREEZE_BLOCKS + 1).is_err());
        assert!(with(ACTION_THAW, 0).is_ok());
        assert!(with(ACTION_THAW, 1).is_err());
        assert!(with(3, 0).is_err());
    }

    #[test]
    fn test_committee_list_and_submit_votes_inputs() {
        let rng = &mut TestRng::default();
        let keys: Vec<_> = (0..7).map(|_| PrivateKey::<CurrentNetwork>::new(rng).unwrap()).collect();
        let members: Vec<_> = keys.iter().map(|key| Address::try_from(key).unwrap()).collect();
        let (list, count) = committee_list(members.clone()).unwrap();
        assert_eq!(count, 7);
        assert_eq!(list.len(), COMMITTEE_LIST_LENGTH);
        // The members come first, strictly increasing by field cast; the rest is the zero address.
        let fields: Vec<_> = list[..7].iter().map(|address| address.to_field().unwrap()).collect();
        assert!(fields.windows(2).all(|pair| pair[0] < pair[1]));
        assert!(list[7..].iter().all(|address| *address == Address::zero()));
        // Bad committees are refused.
        assert!(committee_list::<CurrentNetwork>(vec![]).is_err());
        assert!(committee_list(vec![members[0], members[0]]).is_err());
        let too_many: Vec<_> = (0..=COMMITTEE_LIST_LENGTH)
            .map(|_| Address::try_from(PrivateKey::<CurrentNetwork>::new(rng).unwrap()).unwrap())
            .collect();
        assert!(committee_list(too_many).is_err());

        // Members 0 and 3 sign: their slots' bits are set, and every other slot carries the filler.
        let literal = FreezeVote { network: 0, action: ACTION_THAW, duration: 0, nonce: 0, expires: 10 }.literal();
        let fields = Value::<CurrentNetwork>::from_str(&literal).unwrap().to_fields().unwrap();
        let signers = [0, 3];
        let (mask, signatures) = signed_slots(&list, |member| {
            signers
                .iter()
                .find(|index| members[**index] == *member)
                .map(|index| keys[*index].sign(&fields, rng).unwrap())
        })
        .unwrap();
        assert_eq!(mask.count_ones(), 2);
        let filler = filler_signature::<CurrentNetwork>().unwrap();
        assert_eq!(filler, filler_signature::<CurrentNetwork>().unwrap());
        for (slot, member) in list.iter().enumerate() {
            let signed = mask & (1 << slot) != 0;
            assert_eq!(signed, signers.iter().any(|index| members[*index] == *member), "slot {slot}");
            assert_eq!(signed, signatures[slot].verify(member, &fields), "slot {slot}");
            if !signed {
                assert_eq!(signatures[slot], filler);
            }
        }
        // The inputs have the program's types and lengths.
        let inputs = submit_votes_inputs(&list[..7], count, mask, &signatures[..7], &literal).unwrap();
        assert_eq!(inputs.len(), 5);
        for index in [0, 3] {
            assert!(
                matches!(&inputs[index], Value::Plaintext(Plaintext::Array(elements, _)) if elements.len() == COMMITTEE_LIST_LENGTH)
            );
        }
        assert_eq!(inputs[1].to_string(), "7u32");
        assert_eq!(inputs[2].to_string(), format!("{mask}u128"));
        assert_eq!(FreezeVote::from_value(&inputs[4]).unwrap(), FreezeVote::parse::<CurrentNetwork>(&literal).unwrap());
    }

