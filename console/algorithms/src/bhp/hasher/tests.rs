// Deterministic input of a given length.
fn bits(len: usize) -> Vec<bool> {
    let mut rng = TestRng::from_seed(1012147);
    (0..len).map(|_| bool::rand(&mut rng)).collect()
}

/// Input lengths to test.
fn representative_lengths(min_len: usize, max_len: usize) -> Vec<usize> {
    let mid = (min_len + max_len) / 2;
    let mut v = vec![
        min_len,
        min_len + 1,
        min_len + BHP_CHUNK_SIZE - 1,
        min_len + BHP_CHUNK_SIZE,
        min_len + BHP_CHUNK_SIZE + 1,
        mid,
        mid - (mid % BHP_CHUNK_SIZE),
        max_len - 2 * BHP_CHUNK_SIZE,
        max_len - BHP_CHUNK_SIZE,
        max_len - 1,
        max_len,
    ];
    v.sort_unstable();
    v.dedup();
    v
}

macro_rules! bhp_hasher_uncompressed_vector_test {
    ($test_name:ident, $nw:literal, $ws:literal, $domain:literal, $expectations:ident) => {
        #[test]
        fn $test_name() -> Result<()> {
            type H = BHPHasher<Console, $nw, $ws>;
            let hasher = H::setup($domain)?;
            let window_size = $ws;
            let min_len = H::MIN_BITS + 1;
            let max_len = H::MAX_BITS;
            let lengths = representative_lengths(min_len, max_len);
            let expected: &[(usize, [u8; 32])] = &$expectations[..];

            assert_eq!(
                lengths.len(),
                expected.len(),
                "{}: representative_lengths vs expectations row count",
                stringify!($test_name)
            );

            let too_short = bits(window_size as usize * BHP_CHUNK_SIZE);
            assert!(hasher.hash_uncompressed(&too_short).is_err());
            assert!(hasher.hash_uncompressed(&bits(max_len + 1)).is_err());

            for (i, &n) in lengths.iter().enumerate() {
                assert_eq!(n, expected[i].0, "{}: length mismatch at index {i}", stringify!($test_name));
                let input = bits(n);
                assert_eq!(input.len(), n);
                let digest = hasher.hash_uncompressed(&input)?;
                let bytes = digest.to_bytes_le()?;
                assert_eq!(
                    digest,
                    hasher.hash_uncompressed(&input)?,
                    "determinism check for {} at length {n}",
                    stringify!($test_name)
                );
                assert_eq!(
                    bytes.as_slice(),
                    &expected[i].1[..],
                    "expectation mismatch for {} at input length {n}",
                    stringify!($test_name)
                );
            }

            Ok(())
        }
    };
}

fn assert_bases_are_nonzero<const NUM_WINDOWS: u8, const WINDOW_SIZE: u8>(
    hasher: &BHPHasher<Console, NUM_WINDOWS, WINDOW_SIZE>,
) {
    for window in hasher.bases().iter() {
        for base in window {
            assert!(!base.is_zero());
        }
    }
    for base in hasher.random_base().iter() {
        assert!(!base.is_zero());
    }
}

#[test]
fn test_window_sum_is_below_the_group_order() -> Result<()> {
    let modulus = <Console as Environment>::Scalar::modulus();
    for window_size in 1..=63 {
        let bound = BHPHasher::<Console, 1, 1>::window_sum_bound(window_size)?;
        assert!(bound < modulus, "window {window_size} sum meets the group order");
    }
    let bound = BHPHasher::<Console, 1, 1>::window_sum_bound(64)?;
    assert!(bound >= modulus, "window 64 is the first sum that meets the group order");
    assert!(BHPHasher::<Console, 1, 1>::window_sum_bound(65).is_err());
    Ok(())
}

#[test]
fn test_setup_rejects_a_window_past_the_cap() {
    let error = BHPHasher::<Console, 1, 64>::setup("BHPWindowCap").unwrap_err().to_string();
    assert!(
        error.contains("BHP window sum must be below the group order"),
        "window 64 must fail the group-order check, got {error}"
    );
}

#[test]
fn test_setup_bases_are_nonzero() -> Result<()> {
    // The deployed 256-bit parameters, and the largest window this scalar field accepts.
    assert_bases_are_nonzero(&BHPHasher::<Console, 3, 57>::setup("AleoBHP256")?);
    assert_bases_are_nonzero(&BHPHasher::<Console, 1, 63>::setup("BHPWindowCap")?);
    Ok(())
}

